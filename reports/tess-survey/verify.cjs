// Run with Playwright available in NODE_PATH. Uses installed Chrome; no server.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({headless:true,executablePath:process.env.TESS_CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[],remote=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  page.on('request',r=>{if(/^https?:/.test(r.url()))remote.push(r.url());});
  await page.goto(pathToFileURL(path.join(__dirname,'index.html')).href);
  await page.waitForFunction(()=>!!window.tessExplorer);
  await page.waitForTimeout(200);
  const geometry=await page.evaluate(()=>{
    const X=window.tessExplorer, t=X.state.time, s=X.sectorAt(t);
    const optical=X.objects.satellite.quaternion;
    const v=new THREE.Vector3(0,0,1).applyQuaternion(optical),a=s.pointing[0]*Math.PI/180,d=s.pointing[1]*Math.PI/180;
    const target=X.world([Math.cos(d)*Math.cos(a),Math.cos(d)*Math.sin(a),Math.sin(d)]);
    const error=v.angleTo(target)*180/Math.PI;
    const i=X.data.stars.findIndex(s=>s[3]==='Pi Mensae');
    X.selectStar(i,false);
    const pi=document.getElementById('star-detail').textContent;
    const q0=X.objects.satellite.quaternion.clone(),e0=new THREE.Vector3(1,0,0).applyQuaternion(X.objects.earth.quaternion);
    X.setTime(t+6*3600);
    const e1=new THREE.Vector3(1,0,0).applyQuaternion(X.objects.earth.quaternion);
    const spin=e0.angleTo(e1)*180/Math.PI,attitude=q0.angleTo(X.objects.satellite.quaternion);
    X.setTime(t);
    return {sectors:X.data.sectors.length,stars:X.data.stars.length,opticalErrorDeg:error,earthSixHourRotationDeg:spin,attitudeChange:attitude,pi};
  });
  assert.equal(geometry.sectors,122);
  assert(geometry.opticalErrorDeg<.00001);
  assert(geometry.earthSixHourRotationDeg>90&&geometry.earthSixHourRotationDeg<90.4);
  assert(geometry.attitudeChange<1e-7);
  assert.match(geometry.pi,/Camera 4 · CCD 2/);
  await page.screenshot({path:path.join(__dirname,'assets','sky-final.png')});
  await page.locator('#date').fill('2026-01-18T12:00');
  await page.locator('#date').dispatchEvent('change');
  assert.equal(await page.locator('#sector-number').textContent(),'Sector 1751');
  await page.locator('#date').fill('2026-01-23T12:00');
  await page.locator('#date').dispatchEvent('change');
  assert.equal(await page.locator('#sector-number').textContent(),'Sector 99');
  await page.locator('#date').fill('2018-08-08T12:00');
  await page.locator('#date').dispatchEvent('change');
  assert.equal(await page.locator('#status').textContent(),'Downlink / gap');
  await page.locator('[data-year="2"]').click();
  assert.equal(await page.locator('#sector-number').textContent(),'Sector 14');
  await page.locator('#sector-select').selectOption('26');
  assert.equal(await page.locator('#sector-number').textContent(),'Sector 26');
  await page.locator('#previous').click();
  assert.equal(await page.locator('#sector-number').textContent(),'Sector 25');
  await page.locator('#next').click();
  assert.equal(await page.locator('#sector-number').textContent(),'Sector 26');
  await page.locator('#show-coverage').check();
  assert(await page.locator('#coverage-key').isVisible());
  await page.screenshot({path:path.join(__dirname,'assets','coverage-final.png')});
  await page.locator('#camera-list input').nth(2).uncheck();
  assert.equal(await page.evaluate(()=>window.tessExplorer.objects.field.children[2].visible),false);
  await page.locator('#camera-list input').nth(2).check();
  await page.locator('[data-view="orbit"]').click();
  assert.equal(await page.evaluate(()=>window.tessExplorer.state.view),'orbit');
  const radiusError=await page.evaluate(()=>{const X=window.tessExplorer,v=X.world(X.sample(X.data.tess,X.state.time)).multiplyScalar(1/6371);return v.distanceTo(X.objects.satellite.position);});
  assert(radiusError<1e-10);
  await page.screenshot({path:path.join(__dirname,'assets','orbit-final.png')});
  await page.locator('[data-view="solar"]').click();
  assert.equal(await page.evaluate(()=>window.tessExplorer.state.view),'solar');
  await page.screenshot({path:path.join(__dirname,'assets','solar-final.png')});
  await page.locator('#focus-earth').click();
  const t0=await page.evaluate(()=>window.tessExplorer.state.time);
  await page.locator('#play').click();
  await page.waitForTimeout(350);
  await page.locator('#play').click();
  const elapsed=await page.evaluate(t=>window.tessExplorer.state.time-t,t0);
  assert(elapsed>1000);
  await page.locator('[data-view="sky"]').click();
  const target0=await page.evaluate(()=>window.tessExplorer.controls.target.toArray());
  const box=await page.locator('#scene').boundingBox();
  await page.keyboard.down('Shift');
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
  await page.mouse.down();await page.mouse.move(box.x+box.width/2+70,box.y+box.height/2+20,{steps:6});await page.mouse.up();
  await page.keyboard.up('Shift');
  await page.waitForTimeout(100);
  const target1=await page.evaluate(()=>window.tessExplorer.controls.target.toArray());
  assert(Math.hypot(...target0.map((v,i)=>v-target1[i]))>.01);
  const radius0=await page.evaluate(()=>window.tessExplorer.camera.position.distanceTo(window.tessExplorer.controls.target));
  await page.mouse.wheel(0,-200);await page.waitForTimeout(100);
  const radius1=await page.evaluate(()=>window.tessExplorer.camera.position.distanceTo(window.tessExplorer.controls.target));
  assert(radius1<radius0);
  await page.locator('#scene').focus();
  const position0=await page.evaluate(()=>window.tessExplorer.camera.position.toArray());
  await page.keyboard.press('ArrowRight');
  const position1=await page.evaluate(()=>window.tessExplorer.camera.position.toArray());
  assert(Math.hypot(...position0.map((v,i)=>v-position1[i]))>1);
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(150);
  await page.locator('#reset-view').click();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(__dirname,'assets','mobile-final.png'),fullPage:true});
  // Opened as a file, Run pipeline plays the embedded sample: Mission Control opens and the star-system stage comes up.
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('#run-btn').click();
  assert(await page.locator('#mc').isVisible());
  assert.match(await page.locator('#mc-proc-t').textContent(),/live\.py/);
  assert.equal(await page.evaluate(()=>window.tessExplorer.mission.replay.name),'sample run');
  await page.locator('#mc-speed').selectOption('4');
  await page.waitForSelector('#mc-stage.on',{timeout:30000});
  assert.deepEqual(errors,[]);
  assert.deepEqual(remote,[]);
  const result={geometry,offlineRequests:remote.length,browserErrors:errors,interactionChecks:'sector jumps, comet window, gaps, year change, coverage, camera toggles, views, playback, pan, zoom, keyboard rotation, responsive layout, Run pipeline sample replay',pass:true};
  fs.writeFileSync(path.join(__dirname,'assets','browser-validation.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
